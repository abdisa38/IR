interface LanguageContextType {
  language: Language
  setLanguage: Dispatch<SetStateAction<Language>>
  t: (key: string, fallback?: string, params?: Record<string, string | number>) => string
}

const LanguageContext = createContext<LanguageContextType | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('ilillii_lang')
      if (saved === 'am' || saved === 'en' || saved === 'om') return saved
    } catch {}
    return 'om'
  })

  const setLanguage: Dispatch<SetStateAction<Language>> = (val) => {
    setLanguageState((prev) => {
      const next = typeof val === 'function' ? val(prev) : val
      try {
        localStorage.setItem('ilillii_lang', next)
        window.dispatchEvent(new CustomEvent('ilillii-language-changed', { detail: next }))
      } catch {}
      return next
    })
  }

  const t = (key: string, fallback?: string, params?: Record<string, string | number>): string => {
    const langDict = translations[language] || translations.om
    let text = (langDict && langDict[key]) || (translations.en && translations.en[key]) || fallback || key
    if (params) {
      Object.entries(params).forEach(([paramKey, val]) => {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val))
      })
    }
    return text
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('LanguageProvider is required')
  return context
}
